#!/usr/bin/env python3
"""Embed the web UI in the executable as a single HTML document.

The generated HTML inlines CSS and JavaScript. A strict CSP uses SHA-256 hashes
so no unsafe-inline directive is needed. Run this after editing src/web.

Usage:
  python3 packaging/embed_web.py
  python3 packaging/embed_web.py --check
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "src" / "web"
HEADER = ROOT / "include" / "cmdb" / "web_bundle.h"
SOURCE = ROOT / "src" / "web_bundle.c"


def csp_hash(data: bytes) -> str:
    digest = hashlib.sha256(data).digest()
    return "'sha256-" + base64.b64encode(digest).decode("ascii") + "'"


def c_byte_array(data: bytes) -> str:
    lines: list[str] = []
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        lines.append("  " + ", ".join("0x%02x" % byte for byte in chunk) + ",")
    lines.append("  0x00")
    return "\n".join(lines)


def generate_html() -> tuple[bytes, bytes, bytes]:
    html = (WEB / "index.html").read_text(encoding="utf-8")
    css = (WEB / "style.css").read_bytes()
    js = (WEB / "app.js").read_bytes()

    if b"</script" in js.lower() or b"</style" in css.lower():
        raise SystemExit("web assets contain an unsafe closing tag")

    html = re.sub(
        r'<meta http-equiv="Content-Security-Policy"[^>]*>\s*',
        "",
        html,
        count=1,
    )
    html = html.replace(
        '  <link rel="stylesheet" href="style.css">\n', "", 1
    )
    html = html.replace(
        '  <script src="app.js" defer></script>\n', "", 1
    )
    if 'style.css' in html or 'app.js' in html:
        raise SystemExit("could not remove external asset references")

    csp = (
        "default-src 'none'; "
        f"script-src {csp_hash(js)}; "
        f"style-src {csp_hash(css)}; "
        "img-src data:; "
        "connect-src 'none'; "
        "object-src 'none'; "
        "base-uri 'none'; "
        "form-action 'none';"
    )
    html = html.replace(
        '  <meta charset="utf-8">\n',
        '  <meta charset="utf-8">\n'
        f'  <meta http-equiv="Content-Security-Policy" content="{csp}">\n',
        1,
    )
    css_text = css.decode("utf-8")
    js_text = js.decode("utf-8")
    # The hash is over the exact text content of <style>/<script>, so do not
    # add whitespace inside those elements.
    html = html.replace(
        '</head>',
        '<style>' + css_text + '</style>\n</head>',
        1,
    )
    html = html.replace(
        '</body>',
        '<script>' + js_text + '</script>\n</body>',
        1,
    )
    return html.encode("utf-8"), css, js


def main() -> int:
    html, css, js = generate_html()
    source_text = (
        "/* Generated by packaging/embed_web.py. Do not edit. */\n"
        '#include "cmdb/web_bundle.h"\n\n'
        "static const unsigned char cmdb_web_bundle_data[] = {\n"
        + c_byte_array(html)
        + "\n};\n\n"
        "const char *const cmdb_web_bundle_html =\n"
        "  (const char *)cmdb_web_bundle_data;\n"
    )
    header_text = """\
#ifndef CMDB_WEB_BUNDLE_H
#define CMDB_WEB_BUNDLE_H

#ifdef __cplusplus
extern "C" {
#endif

extern const char *const cmdb_web_bundle_html;

#ifdef __cplusplus
}
#endif

#endif /* CMDB_WEB_BUNDLE_H */
"""
    if "--check" in sys.argv:
        ok = True
        if not SOURCE.exists() or SOURCE.read_text(encoding="utf-8") != source_text:
            print(f"out of date: {SOURCE}", file=sys.stderr)
            ok = False
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != header_text:
            print(f"out of date: {HEADER}", file=sys.stderr)
            ok = False
        if not ok:
            print("run: python3 packaging/embed_web.py", file=sys.stderr)
            return 1
        print(f"web bundle is up to date ({len(html)} bytes)")
        return 0

    HEADER.parent.mkdir(parents=True, exist_ok=True)
    SOURCE.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(header_text, encoding="utf-8")
    SOURCE.write_text(source_text, encoding="utf-8")
    print(f"wrote {SOURCE} ({len(html)} bytes of HTML)")
    print(f"wrote {HEADER}")
    print(f"CSS sha256: {csp_hash(css)}")
    print(f"JS  sha256: {csp_hash(js)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
